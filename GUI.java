    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String name = jTextField1.getText();

            double javaScore =
                    Double.parseDouble(jTextField2.getText());

            double databaseScore =
                    Double.parseDouble(jTextField5.getText());

            double networkingScore =
                    Double.parseDouble(jTextField4.getText());

            double mathScore =
                    Double.parseDouble(jTextField6.getText());

            scores[0] = javaScore;
            scores[1] = databaseScore;
            scores[2] = networkingScore;
            scores[3] = mathScore;

            double total = calculateTotal(scores);
            double average = calculateAverage(scores);
            double highest = findHighest(scores);
            double lowest = findLowest(scores);

            jLabel10.setText(String.valueOf(total));
            jLabel12.setText(String.format("%.2f", average));
            jLabel14.setText(String.valueOf(highest));
            jLabel16.setText(String.valueOf(lowest));

            if (average >= 75) {
                jLabel18.setText("PASSED");
            } else {
                jLabel18.setText("FAILED");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter a valid number in all four score fields.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

